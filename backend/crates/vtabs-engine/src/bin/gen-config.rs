//! Mirrors Rust-owned option descriptors into Lua runtime and LuaCATS schemas.

use std::path::PathBuf;
use std::process::exit;

use vtabs_engine::settings::schema::{Descriptor, Kind, identity, options};
use vtabs_engine::settings::value::Value;

fn lua_string(value: &str) -> String {
    if value.contains('"') && !value.contains('\'') {
        let value = value
            .replace('\\', "\\\\")
            .replace('\n', "\\n")
            .replace('\r', "\\r")
            .replace('\t', "\\t");
        return format!("'{value}'");
    }
    serde_json::to_string(value).expect("a Rust string is representable as a Lua string")
}

fn lua_number(value: f64) -> String {
    if value.fract() == 0.0 && value >= i64::MIN as f64 && value <= i64::MAX as f64 {
        format!("{}", value as i64)
    } else {
        serde_json::to_string(&value).expect("schema numbers are finite")
    }
}

fn lua_value(value: &Value) -> String {
    match value {
        Value::Null => "nil".to_owned(),
        Value::Bool(value) => value.to_string(),
        Value::Number(value) => lua_number(*value),
        Value::String(value) => lua_string(value),
        Value::List(values) => {
            let values = values.iter().map(lua_value).collect::<Vec<_>>().join(", ");
            if values.is_empty() {
                "{}".to_owned()
            } else {
                format!("{{ {values} }}")
            }
        }
        Value::Table(values) => {
            let values = values
                .iter()
                .map(|(key, value)| format!("[{}] = {}", lua_string(key), lua_value(value)))
                .collect::<Vec<_>>()
                .join(", ");
            if values.is_empty() {
                "{}".to_owned()
            } else {
                format!("{{ {values} }}")
            }
        }
    }
}

fn field(out: &mut String, key: &str, value: &str) {
    out.push_str(&format!("    {key} = {value},\n"));
}

fn descriptor(out: &mut String, option: &Descriptor) {
    out.push_str("  {\n");
    field(out, "key", &lua_string(option.key));
    field(out, "type", &lua_string(option.kind.lua_name()));
    field(out, "apply_mode", &lua_string(option.apply_mode.name()));
    if let Some(host_key) = option.host_key {
        field(out, "host_key", &lua_string(host_key));
    }
    if !option.policy_paths.is_empty() {
        let paths = option
            .policy_paths
            .iter()
            .map(|path| lua_string(path))
            .collect::<Vec<_>>()
            .join(", ");
        field(out, "policy_paths", &format!("{{ {paths} }}"));
    }
    if let Some(value) = &option.default {
        field(out, "default", &lua_value(value));
    }
    if option.integer {
        field(out, "integer", "true");
    }
    if let Some(value) = option.min {
        field(out, "min", &lua_number(value));
    }
    if let Some(value) = option.max {
        field(out, "max", &lua_number(value));
    }
    if !option.allowed.is_empty() {
        field(
            out,
            "enum",
            &lua_value(&Value::List(option.allowed.clone())),
        );
    }
    if !option.aliases.is_empty() {
        let aliases = option
            .aliases
            .iter()
            .map(|(from, to)| format!("[{}] = {}", lua_value(from), lua_value(to)))
            .collect::<Vec<_>>()
            .join(", ");
        field(out, "alias", &format!("{{ {aliases} }}"));
    }
    if let Some(kind) = option.list_of {
        field(out, "of", &lua_string(kind.lua_name()));
    }
    if option.container {
        field(out, "container", "true");
    }
    if option.open {
        field(out, "open", "true");
    }
    if let Some(value) = option.docs {
        field(out, "docs", &value.to_string());
    }
    for (key, value) in [
        ("shown", option.shown),
        ("label", option.label),
        ("group", option.group),
        ("values", option.values),
        ("help", option.help),
    ] {
        if let Some(value) = value {
            field(out, key, &lua_string(value));
        }
    }
    out.push_str("  },\n");
}

fn schema_contents() -> String {
    let mut out = String::from(
        "-- Generated by `just gen-config` from vtabs-engine settings/schema.rs; do not edit.\n-- luacheck: ignore 631\nlocal options = {\n",
    );
    for option in options() {
        descriptor(&mut out, option);
    }
    out.push_str("}\n");
    out.push_str(&format!(
        "options.schema_id = {}\n",
        lua_string(&identity())
    ));
    out.push_str("return options\n");
    out
}

fn schema_target() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../plugin/vtabs/gen/schema.lua")
}

fn lua_type_literal(value: &Value) -> String {
    match value {
        Value::Null => "nil".to_owned(),
        Value::Bool(value) => value.to_string(),
        Value::Number(value) => lua_number(*value),
        Value::String(value) => lua_string(value),
        Value::List(_) | Value::Table(_) => "unknown".to_owned(),
    }
}

fn enum_type(option: &Descriptor) -> String {
    let mut values = Vec::new();
    for value in option
        .allowed
        .iter()
        .chain(option.aliases.iter().map(|(from, _)| from))
    {
        let value = lua_type_literal(value);
        if !values.contains(&value) {
            values.push(value);
        }
    }
    values.join("|")
}

fn pascal_case(value: &str) -> String {
    value
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().chain(chars).collect(),
                None => String::new(),
            }
        })
        .collect()
}

fn class_name(path: &str) -> String {
    let suffix = path.split('.').map(pascal_case).collect::<String>();
    format!("VerticalTabs.{suffix}")
}

fn has_children(path: &str) -> bool {
    let prefix = format!("{path}.");
    options()
        .iter()
        .any(|option| option.key.starts_with(&prefix))
}

fn manual_type(key: &str) -> Option<&'static str> {
    match key {
        "settings" => Some("boolean|VerticalTabs.Settings"),
        "frame" => Some("\"zen\"|false|VerticalTabs.Frame"),
        "popover.width" => Some("\"auto\"|integer"),
        "strip_actions" => Some("VerticalTabs.StripAction[]"),
        "icon_map" => Some("table<string, string>"),
        "title" => Some("VerticalTabs.TitleCallback"),
        "private.env" | "backend.env" => Some("table<string, string>"),
        "keys" => Some("false|VerticalTabs.KeyMap"),
        "theme" => Some("VerticalTabs.Theme"),
        "hooks.filter" => Some("VerticalTabs.FilterCallback"),
        "hooks.footer" => Some("VerticalTabs.FooterCallback"),
        "hooks.theme" => Some("VerticalTabs.ThemeCallback"),
        "hooks.route" => Some("VerticalTabs.RouteCallback"),
        "spaces" => Some("VerticalTabs.Space[]"),
        "backend" => Some("VerticalTabs.Backend"),
        "backend.path" => Some("VerticalTabs.BackendPath"),
        _ => None,
    }
}

fn option_type(option: &Descriptor) -> String {
    if let Some(value) = manual_type(option.key) {
        return value.to_owned();
    }
    if has_children(option.key) {
        return class_name(option.key);
    }
    match option.kind {
        Kind::Any => "unknown".to_owned(),
        Kind::Boolean => "boolean".to_owned(),
        Kind::Number if option.integer => "integer".to_owned(),
        Kind::Number => "number".to_owned(),
        Kind::String => "string".to_owned(),
        Kind::Table if option.open => "table<string, unknown>".to_owned(),
        Kind::Table => "table".to_owned(),
        Kind::List => match option.list_of {
            Some(Kind::Table) => "table[]".to_owned(),
            Some(Kind::Enum) => format!("({})[]", enum_type(option)),
            _ => "unknown[]".to_owned(),
        },
        Kind::Enum => enum_type(option),
        Kind::Function => "function".to_owned(),
    }
}

fn parent_path(path: &str) -> &str {
    path.rsplit_once('.').map_or("", |(parent, _)| parent)
}

fn field_name(path: &str) -> &str {
    path.rsplit_once('.').map_or(path, |(_, field)| field)
}

fn doc_field_name(path: &str) -> String {
    let name = field_name(path);
    if matches!(
        name,
        "and"
            | "break"
            | "do"
            | "else"
            | "elseif"
            | "end"
            | "false"
            | "for"
            | "function"
            | "goto"
            | "if"
            | "in"
            | "local"
            | "nil"
            | "not"
            | "or"
            | "repeat"
            | "return"
            | "then"
            | "true"
            | "until"
            | "while"
            | "public"
            | "protected"
            | "private"
            | "package"
    ) {
        format!("[{}]", lua_string(name))
    } else {
        name.to_owned()
    }
}

fn type_class(out: &mut String, path: &str, name: &str) {
    out.push_str(&format!("---@class (exact) {name}\n"));
    for option in options()
        .iter()
        .filter(|option| parent_path(option.key) == path)
    {
        out.push_str(&format!(
            "---@field {}? {}",
            doc_field_name(option.key),
            option_type(option)
        ));
        if let Some(help) = option.help {
            out.push_str(" # ");
            out.push_str(help);
        }
        out.push('\n');
    }
    out.push('\n');
}

fn types_contents() -> String {
    let mut out = String::from(
        "---@meta\n\n-- Generated by `just gen-config` from vtabs-engine settings/schema.rs; do not edit.\n\n",
    );
    type_class(&mut out, "", "VerticalTabs.Config");
    for option in options().iter().filter(|option| {
        parent_path(option.key).is_empty()
            && has_children(option.key)
            && manual_type(option.key).is_none()
    }) {
        type_class(&mut out, option.key, &class_name(option.key));
    }
    out.pop();
    out
}

fn types_target() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../plugin/types/vertical-tabs-config.d.lua")
}

fn main() {
    let check = std::env::args().nth(1).as_deref() == Some("--check");
    let generated = [
        (schema_target(), schema_contents()),
        (types_target(), types_contents()),
    ];
    if check {
        let mut stale = false;
        for (path, wanted) in &generated {
            match std::fs::read_to_string(path) {
                Ok(have) if have == *wanted => {}
                Ok(_) => {
                    eprintln!("{} is stale; run `just gen-config`", path.display());
                    stale = true;
                }
                Err(error) => {
                    eprintln!("{}: {error}; run `just gen-config`", path.display());
                    stale = true;
                }
            }
        }
        if stale {
            exit(1);
        }
        return;
    }
    for (path, wanted) in generated {
        std::fs::create_dir_all(path.parent().expect("generated file has a parent"))
            .expect("create generated file directory");
        std::fs::write(&path, wanted).expect("write generated file");
        println!("wrote {}", path.display());
    }
}
