//! Mirrors `limits.rs` into `plugin/vtabs/gen/protocol.lua`; `--check` fails when stale.

use std::path::PathBuf;
use std::process::exit;

use vtabs_protocol::limits::{
    CONTROL_PREFIX, CONTROL_TOKEN_MAX_BYTES, FORWARDED_KEY_MAX_BYTES,
    FORWARDED_KEY_MAX_ENCODED_BYTES, FRAME_MAX_AREA, FRAME_MAX_SIDE, INBOX_FILE_MAX_BYTES,
    INBOX_SEQ_DIGITS, INBOX_SESSION_MAX_BYTES, LINE_MAX, MODEL_MAX_SPACES, PASTE_MAX_BYTES,
    PASTE_MAX_ENCODED_BYTES, SETTINGS_BODY_MAX_BYTES, TITLEBAR_PT,
};

fn lua_string(bytes: &[u8]) -> String {
    let mut out = String::from("\"");
    for &byte in bytes {
        match byte {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            0x20..=0x7e => out.push(char::from(byte)),
            _ => out.push_str(&format!("\\x{byte:02x}")),
        }
    }
    out.push('"');
    out
}

fn contents() -> String {
    let rows = [
        ("FRAME_MAX_SIDE", FRAME_MAX_SIDE as u64),
        ("FRAME_MAX_AREA", FRAME_MAX_AREA),
        ("CONTROL_TOKEN_MAX_BYTES", CONTROL_TOKEN_MAX_BYTES as u64),
        ("LINE_MAX", LINE_MAX as u64),
        ("INBOX_SESSION_MAX_BYTES", INBOX_SESSION_MAX_BYTES as u64),
        ("INBOX_SEQ_DIGITS", INBOX_SEQ_DIGITS as u64),
        ("INBOX_FILE_MAX_BYTES", INBOX_FILE_MAX_BYTES as u64),
        ("FORWARDED_KEY_MAX_BYTES", FORWARDED_KEY_MAX_BYTES as u64),
        (
            "FORWARDED_KEY_MAX_ENCODED_BYTES",
            FORWARDED_KEY_MAX_ENCODED_BYTES as u64,
        ),
        ("PASTE_MAX_BYTES", PASTE_MAX_BYTES as u64),
        ("PASTE_MAX_ENCODED_BYTES", PASTE_MAX_ENCODED_BYTES as u64),
        ("MODEL_MAX_SPACES", MODEL_MAX_SPACES as u64),
        ("SETTINGS_BODY_MAX_BYTES", SETTINGS_BODY_MAX_BYTES as u64),
        ("TITLEBAR_PT", u64::from(TITLEBAR_PT)),
    ];
    let mut out = String::from(
        "-- Generated by `just gen-protocol` from vtabs-protocol/src/limits.rs; do not edit.\nreturn {\n",
    );
    for (name, value) in rows {
        out.push_str(&format!("  {name} = {value},\n"));
    }
    out.push_str(&format!(
        "  CONTROL_PREFIX = {},\n",
        lua_string(CONTROL_PREFIX)
    ));
    out.push_str("  THEME_COLOR_FIELDS = {\n");
    for field in vtabs_protocol::payload::THEME_COLOR_FIELDS {
        out.push_str(&format!("    [{:?}] = true,\n", field));
    }
    out.push_str("  },\n  THEME_FRACTION_FIELDS = {\n");
    for field in vtabs_protocol::payload::THEME_FRACTION_FIELDS {
        out.push_str(&format!("    [{:?}] = true,\n", field));
    }
    out.push_str("  },\n  INTENT_NAMES = {\n");
    for name in vtabs_protocol::Intent::NAMES {
        out.push_str(&format!("    [{:?}] = true,\n", name));
    }
    out.push_str("  },\n");
    out.push_str("}\n");
    out
}

fn target() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../plugin/vtabs/gen/protocol.lua")
}

fn main() {
    let check = std::env::args().nth(1).as_deref() == Some("--check");
    let path = target();
    let want = contents();
    if check {
        match std::fs::read_to_string(&path) {
            Ok(have) if have == want => {}
            Ok(_) => {
                eprintln!("{} is stale; run `just gen-protocol`", path.display());
                exit(1);
            }
            Err(err) => {
                eprintln!("{}: {err}; run `just gen-protocol`", path.display());
                exit(1);
            }
        }
        return;
    }
    std::fs::create_dir_all(path.parent().unwrap()).expect("gen dir");
    std::fs::write(&path, want).expect("write protocol.lua");
    println!("wrote {}", path.display());
}
